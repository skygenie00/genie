ROMAN = re.compile(u'^\\s*[\u2160-\u2169]\\s+\\S')
MOA = re.compile(u'^(.*?)[ \\t]*미기출\\s*판례\\s*모아보기[ \\t]*-[ \\t]*(\\d{1,3})[ \\t]*-[ \\t]*$')
MOAHEAD = re.compile(u'^\\s*◈\\s*미기출\\s*판례\\s*모아보기\\s*$')


def moa_of(line):
    """줄 끝 모아보기 쪽 머리면 (머리 앞 글, 쪽) · 아니면 None."""
    m = MOA.match(line or u'')
    return (m.group(1).rstrip(), m.group(2)) if m else None


def _toc_line(ln):
    s = re.sub(u'\\s', u'', ln or u'')
    return bool(re.match(u'^제\\d+[장절]', s)) and s in TOC_JJ


def strip_tail(text):
    """칸 끝 덩이 → (걷은 글, [걷은 줄]) · 없으면 글 그대로."""
    if not text:
        return text, []
    lines = text.split(u'\n')
    got = []
    for i, ln in enumerate(lines):
        m = moa_of(ln)
        if m is None:
            continue
        rest = lines[i + 1:]
        if all((not x.strip()) or MOAHEAD.match(x) or ROMAN.match(x) for x in rest):
            got = [ln.strip()] + [x.strip() for x in rest if x.strip()]
            lines = lines[:i] + ([m[0]] if m[0].strip() else [])
            break
    j, toc = len(lines), 0
    while j > 0:
        x = lines[j - 1]
        if not x.strip():
            j -= 1
            continue
        if _toc_line(x):
            toc += 1
            j -= 1
            continue
        if ROMAN.match(x):
            j -= 1
            continue
        break
    if toc:
        got += [x.strip() for x in lines[j:] if x.strip()]
        lines = lines[:j]
    if not got:
        return text, []
    return u'\n'.join(lines).rstrip(), got


def strip_heads(text):
    """글 칸 → (걷은 글, [(편 번호, 쪽, 걷은 줄 글)]). 머리글뿐인 줄은 줄째 빼고 · 글 뒤 꼬리면 꼬리만."""
    text, tail = strip_tail(text)   # ★ uid_add2 §C-1 — 칸 끝 덩이(모아보기 쪽 머리 · 장 차례) 먼저
    if not text or u'편' not in text:
        return text, [(None, None, x) for x in tail]
    out, got = [], [(None, None, x) for x in tail]
    for ln in text.split(u'\n'):
        h = head_of(ln)
        if h is None:
            out.append(ln)
            continue
        got.append((h[1], h[2], ln.strip()))
        if h[0].strip():
            out.append(h[0])
    t = u'\n'.join(out)
    # 칸 끝에 남은 빈 줄·공백(머리글 줄 앞의 들여쓰기 공백 줄)은 걷는다 — 칸 가운데 줄 모양은 그대로
    if got:
        t = t.rstrip()
    return t, got
