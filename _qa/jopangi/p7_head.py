def head_of(line):
    """줄 끝 머리글이면 (머리글 앞 글, 편 번호, 쪽) · 아니면 None."""
    m = HEAD.search(line)
    if not m:
        return None
    num = int(m.group(2))
    name = re.sub(u'\\s', u'', m.group(3))
    if PYEON.get(num) != name:
        return None
    return line[:m.start()].rstrip(), num, m.group(4)


